export function AudienceSection() {
  const [open, setOpen] = useState<Audience | null>(null);

  return (
    <section className="mx-auto w-full max-w-6xl px-4 py-14 sm:px-6 sm:py-20">
      <h2 className="reveal text-2xl font-bold tracking-tight text-white sm:text-4xl">
        Для кого DevShelf
      </h2>
      <div className="mt-6 flex flex-wrap gap-2 sm:mt-8 sm:gap-3">
        {AUDIENCE.map((a, i) => (
          <button
            key={a.chip}
            onClick={() => setOpen(a)}
            className="reveal card cursor-pointer px-3.5 py-2 text-xs font-medium text-zinc-200 transition-colors hover:!border-lime-300/50 hover:text-white sm:px-4 sm:text-sm"
            style={{ transitionDelay: `${i * 40}ms` }}
          >
            {a.emoji} {a.chip}
          </button>
        ))}
      </div>

      {open && (
        <div
          className="modal-overlay fixed inset-0 z-50 flex items-center justify-center bg-black/70 p-4 backdrop-blur-sm"
          onClick={() => setOpen(null)}
          role="dialog"
          aria-modal="true"
        >
          <div
            className="modal-panel card relative max-h-[85dvh] w-full max-w-lg overflow-y-auto p-6 sm:p-8"
            onClick={(e) => e.stopPropagation()}
          >
            <button
              onClick={() => setOpen(null)}
              className="absolute right-4 top-4 text-xl text-zinc-500 transition-colors hover:text-white"
              aria-label="Закрыть"
            >
              ✕
            </button>
            <div className="text-4xl">{open.emoji}</div>
            <h3 className="mt-3 text-2xl font-extrabold text-white">{open.title}</h3>
            <p className="mt-4 text-sm leading-relaxed text-zinc-300">{open.what}</p>
            <p className="mt-3 text-sm leading-relaxed text-zinc-400">{open.whatFor}</p>
            <div className="mt-5">
              <div className="text-xs font-semibold uppercase tracking-wider text-zinc-500">Что выкладывают</div>
              <div className="mt-2 flex flex-wrap gap-2">
                {open.examples.map((ex) => (
                  <span key={ex} className="rounded-full border border-lime-300/25 bg-lime-300/10 px-3 py-1 text-xs text-lime-200">
                    {ex}
                  </span>
                ))}
              </div>
            </div>
          </div>
        </div>
      )}
    </section>
  );
}
